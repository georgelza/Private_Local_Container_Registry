#!/usr/bin/env bash
################################################################################################################################
#
#   Project               :   Local Registry + vCluster lab
#   File                  :   purge_registry.sh
#   Description           :   Multi-repository delete for the local compose registry (registry:2).
#                             The registry UI (joxit) can only delete tags one repository at a time —
#                             this script is the all-repositories equivalent. Two modes:
#
#                               (default)  API purge — deletes every manifest of every repository via
#                                          DELETE /v2/<name>/manifests/<digest>. Fast, registry stays up.
#                                          Repo NAMES with zero manifests remain in /v2/_catalog
#                                          (registry:2 keeps the on-disk repo dirs) — use --full for a
#                                          zero-repo state.
#                               --full     Volume wipe — stops the registry, removes ./data/registry,
#                                          recreates the container. Zero repositories, zero blobs.
#                                          TLS material is preserved across the wipe (see below).
#   Version               :   v1.0
#   Author                :   George Leonard / georgelza@gmail.com
#
#   Prereq (API mode): REGISTRY_STORAGE_DELETE_ENABLED=true on regis_registry (docker-compose.yml)
#                      — registry:2 refuses DELETE (405) without it.
#
#   Usage:
#     ./scripts/purge_registry.sh                                     # API purge, localhost:$HOST_PORT_REGISTRY (.env)
#     REGISTRY_HOST=5002 ./scripts/purge_registry.sh                  # override the port (e.g. a scratch registry)
#     REGISTRY_CA=/path/to/ca.crt ./scripts/purge_registry.sh         # custom CA for TLS verification
#     ./scripts/purge_registry.sh --full                              # stop + volume wipe + recreate (zero repos)
#
################################################################################################################################

set -euo pipefail

SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
PROJECT_DIR="$SCRIPT_DIR/.."

MODE="api"
if [ "${1:-}" = "--full" ]; then
    MODE="full"
fi

die() { echo "ERROR: $*" >&2; exit 1; }

# Registry TLS configuration
# Default CA cert location (generated by the Makefile `certs` target)
REGISTRY_CA="${REGISTRY_CA:-$PROJECT_DIR/data/registry/certs/ca.crt}"
REGISTRY_HOST="${REGISTRY_HOST:-$(grep -E '^HOST_PORT_REGISTRY=' "$PROJECT_DIR/.env" | cut -d= -f2)}"
REGISTRY_SCHEME="https"
BASE="${REGISTRY_SCHEME}://localhost:${REGISTRY_HOST}/v2"

CURL_OPTS=(-fsS --cacert "$REGISTRY_CA")

MANIFEST_ACCEPT='application/vnd.docker.distribution.manifest.v2+json,application/vnd.docker.distribution.manifest.list.v2+json'
LIST_ACCEPT='application/vnd.docker.distribution.manifest.list.v2+json'

# ── --full: volume wipe (zero repositories) ─────────────────────────────────────────────────────────────────────
if [ "$MODE" = "full" ]; then
    echo "stopping the registry, wiping ${PROJECT_DIR}/data/registry, recreating..."
    ( cd "$PROJECT_DIR" && docker compose -p regis stop regis_registry )

    # Registry data and TLS material share the same host directory. Preserve
    # certificates while removing repository/blob state; otherwise the newly
    # started registry has no server certificate and cannot serve HTTPS.
    REGISTRY_DIR=$PROJECT_DIR/data/registry
    CERTS_DIR="$REGISTRY_DIR/certs"
    TMP_DIR="$(mktemp -d "${TMPDIR:-/tmp}/registry-certs.XXXXXX")"
    cleanup_tmp() { rm -rf "$TMP_DIR"; }
    trap cleanup_tmp EXIT
    if [ -d "$CERTS_DIR" ]; then
        cp -R "$CERTS_DIR" "$TMP_DIR/certs"
    fi
    rm -rf "$REGISTRY_DIR"
    mkdir -p "$REGISTRY_DIR"
    if [ -d "$TMP_DIR/certs" ]; then
        cp -R "$TMP_DIR/certs" "$REGISTRY_DIR/certs"
    else
        die "registry TLS certificates are missing; run make certs before purge"
    fi

    ( cd "$PROJECT_DIR" && docker compose -p regis up -d regis_registry )

    # registry:2 has no shell-based readiness command. Poll the HTTPS API
    # instead of assuming the container has bound the host port immediately.
    CATALOG=""
    for attempt in $(seq 1 30); do
        if CATALOG=$(curl --connect-timeout 2 --max-time 5 "${CURL_OPTS[@]}" "${BASE}/_catalog" 2>/dev/null); then
            break
        fi
        if [ "$attempt" -eq 30 ]; then
            die "registry did not come back up — check: make status"
        fi
        sleep 2
    done
    [ "$(printf '%s' "$CATALOG" | jq -r '.repositories | length')" = "0" ] \
        || die "catalog not empty after wipe: $CATALOG"
    echo "done: registry is empty (0 repositories)"
    echo "re-push everything with: make build"
    exit 0
fi

# ── API purge: delete every manifest of every repository ───────────────────────────────────────────────────────
curl "${CURL_OPTS[@]}" "${BASE}/_catalog" >/dev/null 2>&1 || \
    die "registry unreachable at ${BASE} — is the compose stack up (make -C deploy run)?"

CATALOG=$(curl "${CURL_OPTS[@]}" "${BASE}/_catalog")
REPOS=$(printf '%s' "$CATALOG" | jq -r '.repositories[]')

if [ -z "$REPOS" ]; then
    echo "registry ${BASE} has no repositories — nothing to do"
    exit 0
fi

REPO_COUNT=$(printf '%s\n' "$REPOS" | wc -l | tr -d ' ')
echo "purging ${REPO_COUNT} repositories from ${BASE}"

# Multiple tags can point at the same manifest digest — delete each digest once.
# Space-separated token list (macOS ships bash 3.2 — no associative arrays).
SEEN=""

deleted=0
for repo in $REPOS; do
    tags=$(curl "${CURL_OPTS[@]}" "${BASE}/$repo/tags/list" | jq -r '(.tags // [])[]')
    tag_count=0
    for tag in $tags; do
        # registry:2 DELETE is digest-only — resolve the tag to its manifest digest first.
        # A 404 here means the tag is already dangling — its manifest was deleted via a
        # sibling tag that shared the same digest. Skip it.
        headers=$(curl -sI -H "Accept: ${MANIFEST_ACCEPT}" "${BASE}/$repo/manifests/$tag" "${CURL_OPTS[@]}") \
            || die "HEAD $repo:$tag failed"
        http_code=$(printf '%s' "$headers" | head -1 | awk '{print $2}')
        if [ "$http_code" = "404" ]; then
            continue
        fi
        [ "$http_code" = "200" ] || die "HEAD $repo:$tag -> HTTP $http_code"
        digest=$(printf '%s' "$headers" | grep -i '^docker-content-digest:' | tr -d '\r' | awk '{print $2}')
        ctype=$(printf '%s' "$headers" | grep -i '^content-type:' | tr -d '\r' | awk '{print $2}')
        [ -n "$digest" ] || die "could not resolve a digest for $repo:$tag"
        if [[ "$ctype" == *list* ]]; then
            # multi-arch manifest list: delete the child manifests first, then the list itself.
            children=$(curl "${CURL_OPTS[@]}" -H "Accept: ${LIST_ACCEPT}" "${BASE}/$repo/manifests/$digest" | jq -r '.manifests[].digest')
            for child in $children; do
                case " $SEEN " in
                    *" $child "*) ;;
                    *) curl "${CURL_OPTS[@]}" -X DELETE "${BASE}/$repo/manifests/$child" >/dev/null \
                           || die "DELETE $repo@$child failed (is REGISTRY_STORAGE_DELETE_ENABLED set?)"
                       SEEN="$SEEN $child"
                       deleted=$((deleted + 1)) ;;
                esac
            done
        fi
        case " $SEEN " in
            *" $digest "*) ;;
            *) curl "${CURL_OPTS[@]}" -X DELETE "${BASE}/$repo/manifests/$digest" >/dev/null \
                   || die "DELETE $repo@$digest failed (is REGISTRY_STORAGE_DELETE_ENABLED set?)"
               SEEN="$SEEN $digest"
               deleted=$((deleted + 1)) ;;
        esac
        tag_count=$((tag_count + 1))
    done
    echo "  - ${repo} (${tag_count} tag(s))"
done

# Verify: no manifests remain. Repo names with zero manifests can linger in the catalog —
# that is expected here (registry:2 keeps the on-disk repo dirs); --full removes those too.
leftover=""
for repo in $REPOS; do
    # A repo dir can vanish from storage once its last manifest is gone — treat that as clean.
    resp=$(curl "${CURL_OPTS[@]}" "${BASE}/$repo/tags/list" 2>/dev/null || true)
    case "$resp" in
        ""|*NOT_FOUND*) tags="" ;;
        *) tags=$(printf '%s' "$resp" | jq -r '(.tags // [])[]') ;;
    esac
    [ -z "$tags" ] || leftover="${leftover}${repo} "
done

echo "done: ${deleted} manifest(s) deleted"
if [ -n "$leftover" ]; then
    die "manifests remain in: ${leftover}"
fi
echo "note: ${REPO_COUNT} empty repository name(s) remain in the catalog (no manifests)."
echo "      for a zero-repo state: $0 --full   |   re-push: make build"
